export type MessageKey = keyof typeof en;

/** The keys every locale must translate: the plain messages, without plural variants. */
export type RequiredMessageKey = Exclude<MessageKey, PluralVariantKey>;

/**
 * The shape a locale catalog must satisfy: every plain key present, values widened
 * to `string`. Plural variants (`key_one`, `key_few`, …) are optional because a
 * language only defines the categories its grammar has; `translate.ts` reuses the
 * plain key for the ones it leaves out.
 */
export type Messages = Record<RequiredMessageKey, string> & Partial<Record<MessageKey, string>>;
